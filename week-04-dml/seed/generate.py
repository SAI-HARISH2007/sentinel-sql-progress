emit(f"INSERT INTO transactions (txn_id, account_id, merchant_id, device_id, location_id, amount, txn_time, status) VALUES ({txn_id}, {PERSONA_ACCT}, 1, {PERSONA_DEVICE_KNOWN[0]}, {delhi_loc}, 5000.00, {sql_val(traveller_base)}, 'success');")
txn_id += 1
traveller_base2 = traveller_base + timedelta(minutes=10)
emit(f"INSERT INTO transactions (txn_id, account_id, merchant_id, device_id, location_id, amount, txn_time, status) VALUES ({txn_id}, {PERSONA_ACCT}, 2, {PERSONA_DEVICE_KNOWN[0]}, {chennai_loc}, 12000.00, {sql_val(traveller_base2)}, 'success');")
txn_id += 1
emit("")

# --- Persona 2: Night Owl (Off-Hours) ---
emit("-- Persona: night_owl — Normally 9-18h, sudden 02:30 spend")
