BROWSERS = ["Chrome", "Safari", "Firefox", "Edge", "Samsung Internet"]

# =============================================================================
# Output SQL file
# =============================================================================

out_path = Path(__file__).resolve().parent.parent / "sql" / "20_seed_data.sql"
sql_lines = []

def sql_val(v):
    """Convert a Python value to SQL literal."""
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, (int, float, Decimal)):
        return str(v)
    if isinstance(v, datetime):
        return f"'{v.strftime('%Y-%m-%d %H:%M:%S')}'"
    if isinstance(v, str):
        return "'" + v.replace("'", "\\'") + "'"
    return "'" + str(v) + "'"

def emit(sql):
    sql_lines.append(sql)

# =============================================================================
# Generate Reference Data
# =============================================================================

emit("-- Sentinel Seed Data")
emit("-- Generated by seed/generate.py")
emit("USE sentinel;")
emit("SET autocommit = 0;   -- one big commit at the end: ~100x faster than 15,000 separate commits")
emit("")

# Merchant categories
emit("-- Merchant categories")
for i, (name, desc) in enumerate(MERCHANT_CATEGORIES, 1):
    emit(f"INSERT INTO merchant_categories (category_id, category_name, description) VALUES ({i}, {sql_val(name)}, {sql_val(desc)}) ON DUPLICATE KEY UPDATE category_name=VALUES(category_name);")
emit("")

# Locations
emit("-- Locations")
location_ids = []
for i, (city, state, country, lat, lon) in enumerate(CITIES, 1):
    location_ids.append(i)
    emit(f"INSERT INTO locations (location_id, city, state, country, latitude, longitude) VALUES ({i}, {sql_val(city)}, {sql_val(state)}, {sql_val(country)}, {lat}, {lon}) ON DUPLICATE KEY UPDATE city=VALUES(city);")
emit("")

# Devices
emit("-- Devices")
device_ids = []
for i in range(1, NUM_DEVICES + 1):
    device_ids.append(i)
    dt = random.choice(DEVICE_TYPES)
    os_name = random.choice(OS_LIST)
    browser = random.choice(BROWSERS)
    fp = fake.sha256()
    emit(f"INSERT INTO devices (device_id, device_type, os, browser, fingerprint_hash) VALUES ({i}, {sql_val(dt)}, {sql_val(os_name)}, {sql_val(browser)}, {sql_val(fp)}) ON DUPLICATE KEY UPDATE device_type=VALUES(device_type);")
emit("")

# =============================================================================
# Generate Users & Accounts
# =============================================================================

emit("-- Users")
user_data = []
for i in range(1, NUM_USERS + 1):
    name = fake.name()
    email = f"user{i}@example.com"
    phone = f"+91{random.randint(7000000000, 9999999999)}"
    dob = fake.date_of_birth(minimum_age=18, maximum_age=75)
    created = fake.date_time_between(start_date="-12M", end_date="-1M")
    user_data.append((i, name, email, phone, dob, created))
    emit(f"INSERT INTO users (user_id, full_name, email, phone, date_of_birth, created_at) VALUES ({i}, {sql_val(name)}, {sql_val(email)}, {sql_val(phone)}, {sql_val(dob)}, {sql_val(created)}) ON DUPLICATE KEY UPDATE full_name=VALUES(full_name);")
emit("")

emit("-- Accounts")
account_data = []
acct_id = 1
for uid in range(1, NUM_USERS + 1):
    num_accts = 1 if random.random() < 0.8 else 2
    for _ in range(num_accts):
        atype = "savings" if random.random() < 0.7 else "current"
        bal = round(random.uniform(5000, 500000), 2)
        created = user_data[uid - 1][5] + timedelta(days=random.randint(0, 30))
        account_data.append((acct_id, uid, atype, bal, "active", created))
        emit(f"INSERT INTO accounts (account_id, user_id, account_type, balance, status, created_at) VALUES ({acct_id}, {uid}, {sql_val(atype)}, {bal}, 'active', {sql_val(created)}) ON DUPLICATE KEY UPDATE balance=VALUES(balance);")
        acct_id += 1
emit("")

# =============================================================================
# Generate Merchants
# =============================================================================

emit("-- Merchants")
merchant_data = []
for i in range(1, NUM_MERCHANTS + 1):
    cat_id = random.randint(1, NUM_MERCHANT_CATEGORIES)
    city_idx = random.randint(0, len(CITIES) - 1)
    city, state, country, lat, lon = CITIES[city_idx]
    # Add small random offset to coordinates
    lat += random.uniform(-0.05, 0.05)
    lon += random.uniform(-0.05, 0.05)
    name = fake.company()
    risk = round(random.uniform(0, 0.15), 2)
    merchant_data.append((i, name, cat_id, city, lat, lon, risk))
    emit(f"INSERT INTO merchants (merchant_id, merchant_name, category_id, city, latitude, longitude, risk_score) VALUES ({i}, {sql_val(name)}, {cat_id}, {sql_val(city)}, {round(lat, 6)}, {round(lon, 6)}, {risk}) ON DUPLICATE KEY UPDATE merchant_name=VALUES(merchant_name);")
emit("")

# =============================================================================
# Generate Account-Device Associations
# =============================================================================

emit("-- Account-Device associations")
ad_pairs = set()
for acct in account_data:
    acct_id_val = acct[0]
    num_devices = random.randint(1, 5)
    for _ in range(num_devices):
        did = random.choice(device_ids)
        if (acct_id_val, did) not in ad_pairs:
            ad_pairs.add((acct_id_val, did))
            first = acct[5] + timedelta(days=random.randint(0, 60))
            emit(f"INSERT IGNORE INTO account_devices (account_id, device_id, first_seen) VALUES ({acct_id_val}, {did}, {sql_val(first)});")
emit("")

# =============================================================================
# Generate Transactions
# =============================================================================

emit("-- Transactions")
txn_data = []
base_date = datetime(2026, 1, 1)
end_date = datetime(2026, 9, 1)

def gen_normal_txn(acct_id, txn_time, override_amount=None):
    """Generate a normal (non-fraud) transaction."""
    merchant_id = random.randint(1, NUM_MERCHANTS)
    did = random.choice([d for d in device_ids if (acct_id, d) in ad_pairs] or device_ids[:1])
    loc_id = random.randint(1, NUM_LOCATIONS)
    if override_amount:
        amount = override_amount
    else:
        # Most transactions are small
        amount = round(random.expovariate(1/2000) + 50, 2)
        amount = min(amount, 50000)
    status = random.choices(["success", "pending", "failed"], weights=[0.85, 0.1, 0.05])[0]
    return (acct_id, merchant_id, did, loc_id, amount, txn_time, status)

# CHANGE vs the original generator: the persona account (1) gets NO random background traffic.
# In the original, account 1 also received ~24 random-hour transactions, so 02:xx held 3 of its 64 transactions
# (4.7 %) and the night_owl persona could never trip the "< 2 % of history" off-hours rule.
PERSONA_ACCT = 1
background_accounts = [a for a in account_data if a[0] != PERSONA_ACCT]

txn_id = 1
for _ in range(NUM_TRANSACTIONS):
    acct = random.choice(background_accounts)
    acct_id_val = acct[0]
    txn_time = fake.date_time_between(start_date=base_date, end_date=end_date)
    row = gen_normal_txn(acct_id_val, txn_time)
    emit(f"INSERT INTO transactions (txn_id, account_id, merchant_id, device_id, location_id, amount, txn_time, status) VALUES ({txn_id}, {row[0]}, {row[1]}, {row[2]}, {row[3]}, {row[4]}, {sql_val(row[5])}, {sql_val(row[6])});")
    txn_data.append((txn_id,) + row)
    txn_id += 1
emit("")

# =============================================================================
# Fraud Personas (injected after normal transactions)
# =============================================================================

emit("-- ==============================================")
emit("-- FRAUD PERSONAS")
emit("-- ==============================================")

