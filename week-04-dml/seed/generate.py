# Ensure a known device exists for the persona account
PERSONA_DEVICE_KNOWN = [d for d in device_ids if (PERSONA_ACCT, d) in ad_pairs][:1]
if not PERSONA_DEVICE_KNOWN:
    PERSONA_DEVICE_KNOWN = [1]
    emit(f"INSERT IGNORE INTO account_devices (account_id, device_id, first_seen) VALUES ({PERSONA_ACCT}, 1, '2026-01-01 09:00:00');")
PERSONA_DEVICE_NEW = 999  # A device not in account_devices for acct 1

# --- Build a solid historical baseline for the persona account so that
#     z-score, off-hours, and impossible-travel rules have data to compare.
#     ~40 normal transactions, business hours (9-18h), modest amounts, Mumbai. ---
emit("-- Persona account historical baseline (normal behaviour)")
baseline_start = datetime(2026, 1, 2)
for b in range(40):
    bt = baseline_start + timedelta(days=random.randint(1, 4),
                                    hours=random.randint(9, 18),
                                    minutes=random.randint(0, 59))
    bamt = round(random.uniform(500, 8000), 2)
    emit(f"INSERT INTO transactions (txn_id, account_id, merchant_id, device_id, location_id, amount, txn_time, status) VALUES ({txn_id}, {PERSONA_ACCT}, {random.randint(1, NUM_MERCHANTS)}, {PERSONA_DEVICE_KNOWN[0]}, 1, {bamt}, {sql_val(bt)}, 'success');")
    txn_id += 1
emit("")

# --- Persona 1: Traveller (Impossible Travel) ---
emit("-- Persona: traveller — Txn in Delhi, then Chennai 10 min later")
traveller_base = datetime(2026, 8, 15, 10, 0, 0)
