emit(f"INSERT INTO transactions (txn_id, account_id, merchant_id, device_id, location_id, amount, txn_time, status) VALUES ({txn_id}, {PERSONA_ACCT}, 5, {PERSONA_DEVICE_KNOWN[0]}, 1, 8500.00, {sql_val(night_base)}, 'success');")
txn_id += 1
emit("")

# --- Persona 3: Burst (Velocity) ---
emit("-- Persona: burst — 8 txns in 3 minutes")
burst_base = datetime(2026, 8, 17, 14, 0, 0)
for b in range(8):
    burst_time = burst_base + timedelta(minutes=b * 0.4)  # ~24 seconds apart
    burst_merchant = random.randint(1, NUM_MERCHANTS)
    emit(f"INSERT INTO transactions (txn_id, account_id, merchant_id, device_id, location_id, amount, txn_time, status) VALUES ({txn_id}, {PERSONA_ACCT}, {burst_merchant}, {PERSONA_DEVICE_KNOWN[0]}, 1, {round(random.uniform(100, 5000), 2)}, {sql_val(burst_time)}, 'success');")
    txn_id += 1
emit("")

# --- Persona 4: New Device Big (New Device + High Amount) ---
emit("-- Persona: new_device_big — 95000 from a never-seen device")
big_base = datetime(2026, 8, 18, 11, 0, 0)
emit(f"INSERT INTO devices (device_id, device_type, os, browser, fingerprint_hash) VALUES ({PERSONA_DEVICE_NEW}, 'mobile', 'Android 14', 'Chrome', 'NEVER_SEEN_DEVICE_HASH_001') ON DUPLICATE KEY UPDATE device_type=VALUES(device_type);")
emit(f"INSERT INTO transactions (txn_id, account_id, merchant_id, device_id, location_id, amount, txn_time, status) VALUES ({txn_id}, {PERSONA_ACCT}, 1, {PERSONA_DEVICE_NEW}, 1, 95000.00, {sql_val(big_base)}, 'success');")
txn_id += 1
emit("")

# --- Persona 5: Bad Merchant ---
emit("-- Persona: bad_merchant — Merchant with high alert rate")
# Create a bad merchant (ID 50) and insert many txns there that will be flagged
bad_merchant_base = datetime(2026, 8, 19, 12, 0, 0)
for b in range(15):
    bad_time = bad_merchant_base + timedelta(hours=b)
    emit(f"INSERT INTO transactions (txn_id, account_id, merchant_id, device_id, location_id, amount, txn_time, status) VALUES ({txn_id}, {random.randint(1, NUM_USERS)}, 50, {random.randint(1, NUM_DEVICES)}, {random.randint(1, NUM_LOCATIONS)}, {round(random.uniform(5000, 80000), 2)}, {sql_val(bad_time)}, 'success');")
    txn_id += 1
emit("")

# =============================================================================
# Login history (sample)
# =============================================================================

emit("-- Login history (sample)")
for i in range(200):
    acct = random.choice(account_data)
    did = random.choice(device_ids)
    loc = random.choice(location_ids)
    lt = fake.date_time_between(start_date=base_date, end_date=end_date)
    success = random.random() > 0.05
    emit(f"INSERT INTO login_history (account_id, device_id, location_id, login_time, success) VALUES ({acct[0]}, {did}, {loc}, {sql_val(lt)}, {1 if success else 0});")
emit("")

emit("COMMIT;")

